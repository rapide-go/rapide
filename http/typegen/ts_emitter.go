package typegen

import (
	"fmt"
	"slices"
	"strings"
)

// Emitter renders a Schema IR into a map of filename -> file contents.
// Implement Emitter to add custom codegen targets (e.g. Zod, OpenAPI, Swift, Dart).
type Emitter interface {
	Emit(s *Schema) map[string]string
}

// TSEmitter emits TypeScript definitions (`types.ts`), typed route helpers (`routes.ts`),
// and optionally the Inertia live-props SSE client (`live.ts`).
type TSEmitter struct {
	LiveEndpoint string
	IncludeLive  bool
}

// NewTSEmitter constructs the default TypeScript Emitter.
func NewTSEmitter() *TSEmitter {
	return &TSEmitter{
		LiveEndpoint: "/_inertia/live",
		IncludeLive:  true,
	}
}

// Emit generates `types.ts`, `routes.ts`, and (when IncludeLive is true) `live.ts`.
func (e *TSEmitter) Emit(s *Schema) map[string]string {
	files := map[string]string{
		"types.ts":  e.EmitTypes(s),
		"routes.ts": e.EmitRoutes(s),
	}
	if e.IncludeLive {
		files["live.ts"] = GenerateLiveClient(e.LiveEndpoint)
	}
	return files
}

// EmitTypes renders `types.ts` from a Schema IR.
func (e *TSEmitter) EmitTypes(s *Schema) string {
	var sb strings.Builder
	sb.WriteString("// Code generated by Rapide TypeGen. DO NOT EDIT.\n\n")
	if len(s.Types) == 0 {
		sb.WriteString("export {};\n")
		return sb.String()
	}
	for i, td := range s.Types {
		if i > 0 {
			sb.WriteString("\n\n")
		}
		fmt.Fprintf(&sb, "export interface %s {\n", td.Name)
		for _, f := range td.Fields {
			opt := ""
			if f.Optional {
				opt = "?"
			}
			fmt.Fprintf(&sb, "  %s%s: %s;\n", formatTSPropKey(f.Name), opt, f.TypeExpr)
		}
		sb.WriteByte('}')
	}
	sb.WriteByte('\n')
	return sb.String()
}

// EmitRoutes renders `routes.ts` from a Schema IR.
func (e *TSEmitter) EmitRoutes(s *Schema) string {
	used := map[string]bool{}
	for _, rt := range s.Routes {
		for _, ref := range rt.TypeRefs {
			used[ref] = true
		}
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by Rapide TypeGen. DO NOT EDIT.\n")
	if len(used) > 0 {
		imps := make([]string, 0, len(used))
		for k := range used {
			imps = append(imps, k)
		}
		slices.Sort(imps)
		fmt.Fprintf(&sb, "import type { %s } from './types';\n", strings.Join(imps, ", "))
	}

	sb.WriteString(tsRoutesPrelude)
	sb.WriteString("export const routes = {\n")
	for _, rt := range s.Routes {
		paramSig := ""
		if len(rt.Params) > 0 {
			fields := make([]string, len(rt.Params))
			for i, p := range rt.Params {
				fields[i] = fmt.Sprintf("%s: string | number", p)
			}
			paramSig = fmt.Sprintf("params: { %s }", strings.Join(fields, "; "))
		}
		urlExpr := buildTemplateLiteral(rt.Path)

		fmt.Fprintf(&sb, "  %q: {\n", rt.Name)
		fmt.Fprintf(&sb, "    method: %q as const,\n", rt.Method)
		fmt.Fprintf(&sb, "    url(%s): string { return %s; },\n", paramSig, urlExpr)
		fmt.Fprintf(&sb, "    definition(%s): RouteDefinition { return { url: %s, method: %q }; },\n", paramSig, urlExpr, rt.Method)

		if rt.HasTypedIO {
			var args []string
			if paramSig != "" {
				args = append(args, paramSig)
			}
			bodyArg := "undefined"
			if rt.InType != "" {
				args = append(args, "body: "+rt.InType)
				bodyArg = "body"
			}
			args = append(args, "init?: RequestInit")
			fmt.Fprintf(&sb, "    call(%s): Promise<%s> { return requestJSON<%s>(%s, %q, %s, init); },\n",
				strings.Join(args, ", "), rt.OutType, rt.OutType, urlExpr, rt.Method, bodyArg)
		}
		sb.WriteString("  },\n")
	}
	sb.WriteString("} as const;\n")
	return sb.String()
}

const tsRoutesPrelude = `
export interface RouteDefinition {
  url: string;
  method: string;
}

function readCSRFToken(): string | undefined {
  if (typeof document === 'undefined') return undefined;
  return document.querySelector<HTMLMetaElement>('meta[name="csrf-token"]')?.content || undefined;
}

async function requestJSON<T>(url: string, method: string, body?: unknown, init?: RequestInit): Promise<T> {
  const csrf = readCSRFToken();
  const headers = new Headers(init?.headers);
  if (!headers.has('Accept')) headers.set('Accept', 'application/json');
  if (csrf && !headers.has('X-CSRF-TOKEN')) headers.set('X-CSRF-TOKEN', csrf);
  if (body !== undefined && !headers.has('Content-Type')) headers.set('Content-Type', 'application/json');

  const res = await fetch(url, {
    ...init,
    method,
    credentials: init?.credentials ?? 'same-origin',
    headers,
    ...(body !== undefined ? { body: JSON.stringify(body) } : {}),
  });
  if (!res.ok) {
    const err = await res.json().catch(() => ({ message: res.statusText }));
    throw Object.assign(new Error(err.message ?? res.statusText), { status: res.status, data: err });
  }
  if (res.status === 204 || res.headers.get('content-length') === '0') {
    return undefined as T;
  }
  return res.json() as Promise<T>;
}

`

// GenerateLiveClient emits a zero-dependency TypeScript helper that subscribes to Rapide's
// `/_inertia/live` SSE endpoint and triggers targeted Inertia partial reloads for `liveProps`.
func GenerateLiveClient(endpoint string) string {
	if endpoint == "" || !strings.HasPrefix(endpoint, "/") || strings.ContainsAny(endpoint, "\r\n") {
		endpoint = "/_inertia/live"
	}
	return fmt.Sprintf(`// Code generated by Rapide TypeGen. DO NOT EDIT.

export interface LiveListener {
  channel: { name: string; type: string };
  events: string[];
}

export interface LivePropMeta {
  listeners?: LiveListener[];
  throttle?: number;
}

export interface InertiaReloadRouter {
  reload(options: { only: string[]; preserveScroll?: boolean; preserveState?: boolean }): void;
}

export function connectLiveProps(
  liveProps: Record<string, LivePropMeta> | undefined,
  inertiaRouter: InertiaReloadRouter,
  endpoint = %q,
): () => void {
  if (!liveProps) return () => {};
  const channels = new Set<string>();
  const propListeners: Array<{ prop: string; channel: string; events: string[] }> = [];

  for (const [prop, meta] of Object.entries(liveProps)) {
    for (const l of meta?.listeners ?? []) {
      if (l.channel?.name && l.events?.length) {
        channels.add(l.channel.name);
        propListeners.push({ prop, channel: l.channel.name, events: l.events });
      }
    }
  }
  if (channels.size === 0) return () => {};

  const url = endpoint + '?channels=' + encodeURIComponent(Array.from(channels).join(','));
  const es = new EventSource(url);
  es.addEventListener('live', (msg) => {
    try {
      const payload = JSON.parse((msg as MessageEvent).data) as { channel?: string; event?: string };
      const only = Array.from(new Set(
        propListeners
          .filter((l) => l.channel === payload.channel && (l.events.includes(payload.event ?? '') || l.events.includes('*')))
          .map((l) => l.prop),
      ));
      if (only.length > 0) {
        inertiaRouter.reload({ only, preserveScroll: true, preserveState: true });
      }
    } catch {
      // Ignore malformed frames
    }
  });
  return () => es.close();
}
`, endpoint)
}
