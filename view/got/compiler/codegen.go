package compiler

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

// ComponentMeta stores the signature metadata of a discovered component in `components/*.got`.
type ComponentMeta struct {
	CompKey      string
	FuncName     string
	PropsType    string
	PropsByLower map[string]PropDef // lowercase/no-dash key -> PropDef
}

type generator struct {
	buf      bytes.Buffer
	litBuf   strings.Builder
	registry map[string]ComponentMeta
}

// generateGo compiles a parsed Template into formatted Go source code.
func generateGo(tpl *Template, pkgName string, registry map[string]ComponentMeta) ([]byte, error) {
	if tpl.Frontmatter.Package != "" {
		pkgName = tpl.Frontmatter.Package
	}
	if pkgName == "" {
		pkgName = "views"
	}

	g := &generator{registry: registry}

	// Build body first so we know everything cleanly.
	if err := g.emitNodes(tpl.Nodes); err != nil {
		return nil, fmt.Errorf("got: codegen %s: %w", tpl.RelPath, err)
	}
	g.flushLit()
	bodyCode := g.buf.String()

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by rapide got compiler from %s. DO NOT EDIT.\n\n", tpl.RelPath)
	fmt.Fprintf(&out, "package %s\n\n", pkgName)

	// Imports (deduplicated)
	out.WriteString("import (\n")
	out.WriteString("\t\"io\"\n\n")
	out.WriteString("\t\"github.com/rapide-go/rapide/view/got\"\n")
	seenImp := map[string]bool{
		`"io"`:                                   true,
		`"github.com/rapide-go/rapide/view/got"`: true,
	}
	for _, imp := range tpl.Frontmatter.Imports {
		imp = strings.TrimSpace(imp)
		if imp == "" || seenImp[imp] {
			continue
		}
		seenImp[imp] = true
		fmt.Fprintf(&out, "\t%s\n", imp)
	}
	out.WriteString(")\n\n")

	// Props struct
	fmt.Fprintf(&out, "// %s holds typed props for %s.\n", tpl.PropsType, tpl.FuncName)
	fmt.Fprintf(&out, "type %s struct {\n", tpl.PropsType)
	for _, pr := range tpl.Frontmatter.Props {
		fmt.Fprintf(&out, "\t%s %s\n", pr.Name, pr.Type)
	}
	out.WriteString("}\n\n")

	// Function signature
	if tpl.IsComponent {
		fmt.Fprintf(&out, "// %s renders the <x-%s> component.\n", tpl.FuncName, tpl.CompKey)
		fmt.Fprintf(&out, "func %s(p %s, attrs got.Attrs, slots got.Slots) got.Component {\n", tpl.FuncName, tpl.PropsType)
	} else {
		fmt.Fprintf(&out, "// %s renders %s.\n", tpl.FuncName, tpl.RelPath)
		fmt.Fprintf(&out, "func %s(p %s) got.Component {\n", tpl.FuncName, tpl.PropsType)
	}
	out.WriteString("\treturn got.ComponentFunc(func(w io.Writer) error {\n")

	// Apply prop defaults and bind local variables so templates can write `{{ Title }}` directly.
	for _, pr := range tpl.Frontmatter.Props {
		if pr.Default != "" {
			zeroCheck := zeroValueCheck("p."+pr.Name, pr.Type)
			if zeroCheck != "" {
				fmt.Fprintf(&out, "\t\tif %s {\n\t\t\tp.%s = %s\n\t\t}\n", zeroCheck, pr.Name, pr.Default)
			}
		}
		fmt.Fprintf(&out, "\t\t%s := p.%s\n\t\t_ = %s\n", pr.Name, pr.Name, pr.Name)
	}
	if tpl.IsComponent {
		out.WriteString("\t\t_ = attrs\n\t\t_ = slots\n")
	}

	out.WriteString(bodyCode)
	out.WriteString("\t\treturn nil\n\t})\n}\n")

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("got: gofmt %s: %w\n--- generated ---\n%s", tpl.RelPath, err, out.String())
	}
	return formatted, nil
}

func zeroValueCheck(expr, typ string) string {
	switch strings.TrimSpace(typ) {
	case "string":
		return expr + ` == ""`
	case "int", "int64", "int32", "uint", "uint64", "float64", "float32":
		return expr + ` == 0`
	case "any", "interface{}":
		return expr + ` == nil`
	default:
		if strings.HasPrefix(typ, "*") || strings.HasPrefix(typ, "[]") || strings.HasPrefix(typ, "map[") {
			return expr + ` == nil`
		}
		return ""
	}
}

func (g *generator) writeLit(s string) {
	g.litBuf.WriteString(s)
}

func (g *generator) flushLit() {
	if g.litBuf.Len() == 0 {
		return
	}
	fmt.Fprintf(&g.buf, "\t\tgot.WriteString(w, %s)\n", strconv.Quote(g.litBuf.String()))
	g.litBuf.Reset()
}

func (g *generator) emitNodes(nodes []Node) error {
	for i := 0; i < len(nodes); i++ {
		n := nodes[i]
		if el, ok := n.(*ElementNode); ok && el.IfExpr != "" {
			// Chain :if / :elseif / :else siblings cleanly.
			g.flushLit()
			fmt.Fprintf(&g.buf, "\t\tif %s {\n", normalizeExpr(el.IfExpr))
			if err := g.emitElementWithoutIf(el); err != nil {
				return err
			}
			g.flushLit()
			g.buf.WriteString("\t\t}")

			for {
				nextIdx := nextNonWhitespaceNode(nodes, i+1)
				if nextIdx < 0 {
					break
				}
				nextEl, ok := nodes[nextIdx].(*ElementNode)
				if !ok {
					break
				}
				if nextEl.ElseIfExpr != "" {
					fmt.Fprintf(&g.buf, " else if %s {\n", normalizeExpr(nextEl.ElseIfExpr))
					if err := g.emitElementWithoutIf(nextEl); err != nil {
						return err
					}
					g.flushLit()
					g.buf.WriteString("\t\t}")
					i = nextIdx
					continue
				}
				if nextEl.IsElse {
					g.buf.WriteString(" else {\n")
					if err := g.emitElementWithoutIf(nextEl); err != nil {
						return err
					}
					g.flushLit()
					g.buf.WriteString("\t\t}")
					i = nextIdx
					break
				}
				break
			}
			g.buf.WriteString("\n")
			continue
		}

		if err := g.emitNode(n); err != nil {
			return err
		}
	}
	return nil
}

func nextNonWhitespaceNode(nodes []Node, start int) int {
	for i := start; i < len(nodes); i++ {
		if t, ok := nodes[i].(TextNode); ok && strings.TrimSpace(t.Text) == "" {
			continue
		}
		return i
	}
	return -1
}

func (g *generator) emitNode(n Node) error {
	switch node := n.(type) {
	case TextNode:
		g.writeLit(node.Text)
	case ExprNode:
		g.flushLit()
		fmt.Fprintf(&g.buf, "\t\tgot.WriteEscaped(w, %s)\n", normalizeExpr(node.Expr))
	case RawNode:
		g.flushLit()
		fmt.Fprintf(&g.buf, "\t\tgot.WriteRaw(w, %s)\n", normalizeExpr(node.Expr))
	case GoNode:
		g.flushLit()
		fmt.Fprintf(&g.buf, "\t\t%s\n", node.Code)
	case *ElementNode:
		return g.emitElementWithoutIf(node)
	}
	return nil
}

func (g *generator) emitElementWithoutIf(el *ElementNode) error {
	if el.ForEach != "" {
		g.flushLit()
		hdr, err := compileForHeader(el.ForEach)
		if err != nil {
			return err
		}
		fmt.Fprintf(&g.buf, "\t\t%s {\n", hdr)
		cp := *el
		cp.ForEach = ""
		if err := g.emitElementCore(&cp); err != nil {
			return err
		}
		g.flushLit()
		g.buf.WriteString("\t\t}\n")
		return nil
	}
	return g.emitElementCore(el)
}

func (g *generator) emitElementCore(el *ElementNode) error {
	lowerTag := strings.ToLower(el.Tag)

	// 1. Transparent fragment: <template>
	if lowerTag == "template" {
		return g.emitNodes(el.Children)
	}

	// 2. Slot outlet inside a component: <x-slot /> or <x-slot name="header" />
	if lowerTag == "x-slot" {
		g.flushLit()
		slotName := ""
		for _, a := range el.Attrs {
			if a.Name == "name" {
				slotName = a.Value
			}
		}
		if slotName == "" {
			g.buf.WriteString("\t\tif err := slots.RenderDefault(w); err != nil {\n\t\t\treturn err\n\t\t}\n")
		} else {
			fmt.Fprintf(&g.buf, "\t\tif err := slots.Render(w, %q); err != nil {\n\t\t\treturn err\n\t\t}\n", slotName)
		}
		return nil
	}

	// 3. Component call: <x-*>
	if strings.HasPrefix(lowerTag, "x-") {
		return g.emitComponentCall(el, lowerTag[2:])
	}

	// 4. Standard HTML element
	g.writeLit("<" + el.Tag)

	// If `:attrs` is present, extract `class` / `:class` to merge with forwarded attrs.
	var baseClassExpr string
	hasBaseClass := false
	if el.SpreadAttrs {
		for _, a := range el.Attrs {
			if a.Name == "class" {
				hasBaseClass = true
				if a.Dynamic {
					baseClassExpr = normalizeExpr(a.Value)
				} else {
					baseClassExpr = compileStringExpr(a.Value)
				}
				break
			}
		}
	}

	for _, a := range el.Attrs {
		if el.SpreadAttrs && a.Name == "class" {
			continue // merged via got.WriteAttrs below
		}
		if a.Dynamic {
			g.flushLit()
			fmt.Fprintf(&g.buf, "\t\tgot.WriteAttr(w, %q, %s)\n", a.Name, normalizeExpr(a.Value))
			continue
		}
		if a.Bool {
			g.writeLit(" " + a.Name)
			continue
		}
		if strings.Contains(a.Value, "{{") {
			g.writeLit(" " + a.Name + `="`)
			g.emitInterpolatedAttr(a.Value)
			g.writeLit(`"`)
			continue
		}
		g.writeLit(" " + a.Name + `="` + a.Value + `"`)
	}

	if el.SpreadAttrs {
		g.flushLit()
		if !hasBaseClass {
			baseClassExpr = `""`
		}
		fmt.Fprintf(&g.buf, "\t\tgot.WriteAttrs(w, %s, attrs)\n", baseClassExpr)
	}

	if el.Void {
		g.writeLit(" />")
		return nil
	}
	g.writeLit(">")

	if err := g.emitNodes(el.Children); err != nil {
		return err
	}
	g.writeLit("</" + el.Tag + ">")
	return nil
}

func (g *generator) emitComponentCall(el *ElementNode, compKey string) error {
	meta, ok := g.registry[compKey]
	if !ok {
		return fmt.Errorf("got: unknown component <x-%s> (expected components/%s.got)", compKey, strings.ReplaceAll(compKey, ".", "/"))
	}

	g.flushLit()

	var propFields []string
	var extraAttrs []string
	for _, a := range el.Attrs {
		normKey := strings.ToLower(strings.ReplaceAll(strings.ReplaceAll(a.Name, "-", ""), "_", ""))
		if propDef, isProp := meta.PropsByLower[normKey]; isProp {
			valExpr := ""
			if a.Dynamic {
				valExpr = normalizeExpr(a.Value)
			} else if a.Bool {
				valExpr = "true"
			} else {
				valExpr = compileStringExpr(a.Value)
			}
			propFields = append(propFields, fmt.Sprintf("%s: %s", propDef.Name, valExpr))
		} else {
			valExpr := ""
			if a.Dynamic {
				valExpr = normalizeExpr(a.Value)
			} else if a.Bool {
				valExpr = "true"
			} else {
				valExpr = compileStringExpr(a.Value)
			}
			extraAttrs = append(extraAttrs, fmt.Sprintf("%q: %s", a.Name, valExpr))
		}
	}

	// Split children into named `<x-slot name="...">` / `<x-slot:name>` and default slot.
	namedSlots := make(map[string][]Node)
	var namedOrder []string
	var defaultNodes []Node

	for _, child := range el.Children {
		if cel, ok := child.(*ElementNode); ok {
			lt := strings.ToLower(cel.Tag)
			if lt == "x-slot" {
				sName := ""
				for _, a := range cel.Attrs {
					if a.Name == "name" {
						sName = a.Value
					}
				}
				if sName != "" {
					if _, exists := namedSlots[sName]; !exists {
						namedOrder = append(namedOrder, sName)
					}
					namedSlots[sName] = append(namedSlots[sName], cel.Children...)
					continue
				}
			} else if strings.HasPrefix(lt, "x-slot:") {
				sName := lt[len("x-slot:"):]
				if _, exists := namedSlots[sName]; !exists {
					namedOrder = append(namedOrder, sName)
				}
				namedSlots[sName] = append(namedSlots[sName], cel.Children...)
				continue
			}
		}
		defaultNodes = append(defaultNodes, child)
	}

	hasDefault := false
	for _, dn := range defaultNodes {
		if t, ok := dn.(TextNode); ok && strings.TrimSpace(t.Text) == "" {
			continue
		}
		hasDefault = true
		break
	}

	propsExpr := fmt.Sprintf("%s{%s}", meta.PropsType, strings.Join(propFields, ", "))
	attrsExpr := "nil"
	if len(extraAttrs) > 0 {
		attrsExpr = fmt.Sprintf("got.Attrs{%s}", strings.Join(extraAttrs, ", "))
	}

	fmt.Fprintf(&g.buf, "\t\tif err := %s(%s, %s, got.Slots{\n", meta.FuncName, propsExpr, attrsExpr)
	if hasDefault {
		g.buf.WriteString("\t\t\tDefault: func(w io.Writer) error {\n")
		if err := g.emitNodes(defaultNodes); err != nil {
			return err
		}
		g.flushLit()
		g.buf.WriteString("\t\t\t\treturn nil\n\t\t\t},\n")
	}
	if len(namedOrder) > 0 {
		g.buf.WriteString("\t\t\tNamed: map[string]got.SlotFunc{\n")
		for _, sName := range namedOrder {
			fmt.Fprintf(&g.buf, "\t\t\t\t%q: func(w io.Writer) error {\n", sName)
			if err := g.emitNodes(namedSlots[sName]); err != nil {
				return err
			}
			g.flushLit()
			g.buf.WriteString("\t\t\t\t\treturn nil\n\t\t\t\t},\n")
		}
		g.buf.WriteString("\t\t\t},\n")
	}
	g.buf.WriteString("\t\t}).Render(w); err != nil {\n\t\t\treturn err\n\t\t}\n")
	return nil
}

func (g *generator) emitInterpolatedAttr(val string) {
	rest := val
	for {
		openIdx := strings.Index(rest, "{{")
		if openIdx < 0 {
			g.writeLit(rest)
			return
		}
		g.writeLit(rest[:openIdx])
		afterOpen := rest[openIdx+2:]
		before, after, ok := strings.Cut(afterOpen, "}}")
		if !ok {
			g.writeLit(rest[openIdx:])
			return
		}
		expr := strings.TrimSpace(before)
		if expr != "" {
			g.flushLit()
			fmt.Fprintf(&g.buf, "\t\tgot.WriteEscapedAttr(w, %s)\n", normalizeExpr(expr))
		}
		rest = after
	}
}

// compileStringExpr turns a static attribute string into either a Go quoted string literal
// or a `got.Fmt(...)` call when `{{ expr }}` interpolations are present.
func compileStringExpr(val string) string {
	if !strings.Contains(val, "{{") {
		return strconv.Quote(val)
	}
	var fmtStr strings.Builder
	var args []string
	rest := val
	for {
		openIdx := strings.Index(rest, "{{")
		if openIdx < 0 {
			fmtStr.WriteString(strings.ReplaceAll(rest, "%", "%%"))
			break
		}
		fmtStr.WriteString(strings.ReplaceAll(rest[:openIdx], "%", "%%"))
		afterOpen := rest[openIdx+2:]
		before, after, ok := strings.Cut(afterOpen, "}}")
		if !ok {
			fmtStr.WriteString(strings.ReplaceAll(rest[openIdx:], "%", "%%"))
			break
		}
		expr := strings.TrimSpace(before)
		if expr != "" {
			fmtStr.WriteString("%v")
			args = append(args, normalizeExpr(expr))
		}
		rest = after
	}
	if len(args) == 0 {
		return strconv.Quote(val)
	}
	return fmt.Sprintf("got.Fmt(%q, %s)", fmtStr.String(), strings.Join(args, ", "))
}

// compileForHeader converts Tempest-style `:foreach="post in Posts"` or `:foreach="i, post in Posts"`
// or native Go `:foreach="i, post := range Posts"` into a valid Go `for ... range ...` clause.
func compileForHeader(expr string) (string, error) {
	s := normalizeExpr(strings.TrimSpace(expr))
	if strings.Contains(s, "range ") {
		if strings.HasPrefix(s, "for ") {
			return s, nil
		}
		return "for " + s, nil
	}
	before, after, ok := strings.Cut(s, " in ")
	if !ok {
		return "", fmt.Errorf("got: invalid :foreach %q (expected 'item in Items' or 'i, item := range Items')", expr)
	}
	lhs := strings.TrimSpace(before)
	rhs := strings.TrimSpace(after)
	if strings.Contains(lhs, ",") {
		return fmt.Sprintf("for %s := range %s", lhs, rhs), nil
	}
	return fmt.Sprintf("for _, %s := range %s", lhs, rhs), nil
}

// normalizeExpr converts single-quoted string literals ('foo', ”) inside HTML-attribute
// Go expressions into Go double-quoted string literals ("foo", ""), while preserving
// anything already inside double quotes or backticks.
func normalizeExpr(expr string) string {
	if !strings.ContainsRune(expr, '\'') {
		return expr
	}
	var sb strings.Builder
	sb.Grow(len(expr))
	inDouble := false
	inBacktick := false
	for i := 0; i < len(expr); i++ {
		c := expr[i]
		if inBacktick {
			sb.WriteByte(c)
			if c == '`' {
				inBacktick = false
			}
			continue
		}
		if inDouble {
			sb.WriteByte(c)
			if c == '\\' && i+1 < len(expr) {
				i++
				sb.WriteByte(expr[i])
			} else if c == '"' {
				inDouble = false
			}
			continue
		}
		if c == '`' {
			inBacktick = true
			sb.WriteByte(c)
			continue
		}
		if c == '"' {
			inDouble = true
			sb.WriteByte(c)
			continue
		}
		if c == '\'' {
			// Scan until matching unescaped single quote
			sb.WriteByte('"')
			i++
			for i < len(expr) && expr[i] != '\'' {
				if expr[i] == '\\' && i+1 < len(expr) {
					if expr[i+1] == '\'' {
						sb.WriteByte('\'')
						i += 2
						continue
					}
					sb.WriteByte(expr[i])
					sb.WriteByte(expr[i+1])
					i += 2
					continue
				}
				if expr[i] == '"' {
					sb.WriteString(`\"`)
					i++
					continue
				}
				sb.WriteByte(expr[i])
				i++
			}
			sb.WriteByte('"')
			continue
		}
		sb.WriteByte(c)
	}
	return sb.String()
}
