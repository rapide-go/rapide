package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

// rapideManifest is the optional `rapide.json` file placed at the root of any Rapide package
// to declare Go packages whose init() registers providers via foundation.AddProvider(...).
type rapideManifest struct {
	Providers []string `json:"providers"`
}

type goModuleInfo struct {
	Path string `json:"Path"`
	Dir  string `json:"Dir"`
	Main bool   `json:"Main"`
}

// cmdAdd installs either a local Rapide package directory (e.g. `rapide add ../../alphyx-watch`)
// or a remote Go module (`rapide add github.com/user/pkg`), then runs package auto-discovery.
func cmdAdd(args []string) error {
	if len(args) < 1 {
		return fmt.Errorf("usage: rapide add <local-path | module[@version]>")
	}

	var remoteArgs []string
	for _, arg := range args {
		if info, err := os.Stat(arg); err == nil && info.IsDir() {
			if err := addLocalPackage(arg); err != nil {
				return err
			}
		} else {
			remoteArgs = append(remoteArgs, arg)
		}
	}

	if len(remoteArgs) > 0 {
		getArgs := append([]string{"get"}, remoteArgs...)
		cmd := exec.Command("go", getArgs...)
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go get failed: %w", err)
		}
	}
	return cmdPackageDiscover(nil)
}

func addLocalPackage(dir string) error {
	absTarget, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(filepath.Join(absTarget, "go.mod"))
	if err != nil {
		return fmt.Errorf("local package %q has no go.mod: %w", dir, err)
	}
	modPath := ""
	for line := range strings.SplitSeq(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if after, ok := strings.CutPrefix(line, "module "); ok {
			modPath = strings.TrimSpace(after)
			break
		}
	}
	if modPath == "" {
		return fmt.Errorf("could not parse module path from %s/go.mod", dir)
	}

	cwd, err := os.Getwd()
	if err != nil {
		return err
	}
	relPath, err := filepath.Rel(cwd, absTarget)
	if err != nil {
		relPath = absTarget
	}
	relPath = filepath.ToSlash(relPath)

	edit := exec.Command("go", "mod", "edit",
		"-require="+modPath+"@v0.0.0",
		"-replace="+modPath+"="+relPath,
	)
	edit.Stdout = os.Stdout
	edit.Stderr = os.Stderr
	if err := edit.Run(); err != nil {
		return fmt.Errorf("go mod edit failed: %w", err)
	}
	fmt.Printf("Linked local package %s -> %s\n", modPath, relPath)
	return nil
}

// cmdRemove removes a Go module from go.mod, re-runs package discovery, and tidies go.mod.
func cmdRemove(args []string) error {
	if len(args) < 1 {
		return fmt.Errorf("usage: rapide remove <module>")
	}
	for _, mod := range args {
		cmd := exec.Command("go", "mod", "edit", "-droprequire", mod)
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("go mod edit failed: %w", err)
		}
	}
	if err := cmdPackageDiscover(nil); err != nil {
		return err
	}
	tidy := exec.Command("go", "mod", "tidy")
	tidy.Stdout = os.Stdout
	tidy.Stderr = os.Stderr
	return tidy.Run()
}

// cmdPackageDiscover inspects all installed modules via `go list -m -json all`,
// reads any `rapide.json` manifests, and generates `bootstrap/packages_gen.go`.
func cmdPackageDiscover(_ []string) error {
	cmd := exec.Command("go", "list", "-m", "-json", "all")
	out, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("go list -m failed: %w", err)
	}

	seen := make(map[string]bool)
	var providers []string

	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var mod goModuleInfo
		if err := dec.Decode(&mod); err != nil {
			if err == io.EOF {
				break
			}
			return err
		}
		if mod.Main || mod.Dir == "" {
			continue
		}
		manifestPath := filepath.Join(mod.Dir, "rapide.json")
		raw, err := os.ReadFile(manifestPath)
		if err != nil {
			continue
		}
		var manifest rapideManifest
		if err := json.Unmarshal(raw, &manifest); err != nil {
			return fmt.Errorf("invalid %s: %w", manifestPath, err)
		}
		for _, pkg := range manifest.Providers {
			pkg = strings.TrimSpace(pkg)
			if pkg != "" && !seen[pkg] {
				seen[pkg] = true
				providers = append(providers, pkg)
			}
		}
	}

	slices.Sort(providers)
	return writePackagesGen(providers)
}

func writePackagesGen(providers []string) error {
	dest := filepath.Join("bootstrap", "packages_gen.go")
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return err
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by rapide package:discover. DO NOT EDIT.\n\n")
	sb.WriteString("package bootstrap\n")
	if len(providers) > 0 {
		sb.WriteString("\nimport (\n")
		for _, pkg := range providers {
			fmt.Fprintf(&sb, "\t_ %q\n", pkg)
		}
		sb.WriteString(")\n")
	}

	formatted, err := format.Source([]byte(sb.String()))
	if err != nil {
		return err
	}
	if err := os.WriteFile(dest, formatted, 0o644); err != nil {
		return err
	}

	if len(providers) == 0 {
		fmt.Println("Discovered 0 Rapide packages.")
		return nil
	}
	for _, p := range providers {
		fmt.Println("Discovered Package:", p)
	}
	fmt.Printf("Wrote %s (%d package(s))\n", dest, len(providers))
	return nil
}
